[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$Version,
    [string]$RepositoryRoot
)

$ErrorActionPreference = 'Stop'

if ([string]::IsNullOrWhiteSpace($RepositoryRoot)) {
    $RepositoryRoot = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
}
$Root = [System.IO.Path]::GetFullPath((Resolve-Path -LiteralPath $RepositoryRoot).Path)
$FullVersion = $Version.Trim()

function Join-RepoPath {
    param([string[]]$Parts)
    $path = $Root
    foreach ($part in $Parts) {
        $path = Join-Path $path $part
    }
    return $path
}

$match = [regex]::Match($FullVersion, '^(?<a>[0-9]+)\.(?<b>[0-9]+)\.(?<c>[0-9]+)\.(?<d>[0-9]+)$')
if (-not $match.Success) {
    throw "Version '$Version' is invalid. Use four numeric components such as 140.0.0.0."
}

$Parts = @($match.Groups['a'].Value, $match.Groups['b'].Value, $match.Groups['c'].Value, $match.Groups['d'].Value)
foreach ($part in $Parts) {
    $number = 0
    if (-not [int]::TryParse($part, [ref]$number) -or $number -gt 65535) {
        throw "Version '$Version' contains a component outside the Windows/MSIX range 0..65535."
    }
}
$DisplayVersion = ($Parts[0..2] -join '.')
$Utf8NoBom = New-Object System.Text.UTF8Encoding -ArgumentList $false
$Changed = New-Object System.Collections.Generic.List[string]

function Write-GeneratedText {
    param([string]$Path, [string]$Content)
    $old = $null
    if (Test-Path -LiteralPath $Path) {
        $old = [System.IO.File]::ReadAllText($Path)
    }
    if ($old -ne $Content) {
        $parent = Split-Path -Parent $Path
        if (-not (Test-Path -LiteralPath $parent)) {
            New-Item -ItemType Directory -Force -Path $parent | Out-Null
        }
        [System.IO.File]::WriteAllText($Path, $Content, $Utf8NoBom)
        $Changed.Add($Path) | Out-Null
    }
}

function Update-Text {
    param([string]$Path, [scriptblock]$Transform)
    if (-not (Test-Path -LiteralPath $Path)) {
        return
    }
    $old = [System.IO.File]::ReadAllText($Path)
    $new = & $Transform $old
    if ($new -ne $old) {
        [System.IO.File]::WriteAllText($Path, $new, $Utf8NoBom)
        $Changed.Add($Path) | Out-Null
    }
}

Write-GeneratedText (Join-RepoPath @('VERSION')) ($FullVersion + [Environment]::NewLine)
Write-GeneratedText (Join-RepoPath @('frontend', 'src', 'lib', 'generated-version.ts')) @"
/**
 * Generated from the repository root VERSION file by scripts/set-version.ps1.
 * Do not edit this file manually.
 */
export const APP_VERSION = '$FullVersion';
export const APP_VERSION_DISPLAY = '$DisplayVersion';
"@
Write-GeneratedText (Join-RepoPath @('backend-api', 'app', 'version.py')) @"
"""Generated application version data.

This file is generated from the repository root VERSION file by
scripts/set-version.ps1. Do not edit it manually.
"""

APP_VERSION = "$FullVersion"
APP_VERSION_DISPLAY = "$DisplayVersion"
"@

$dockerfile = Join-RepoPath @('Dockerfile')
Update-Text $dockerfile {
    param($text)
    [regex]::Replace(
        $text,
        '(?m)^([ \t]*ARG[ \t]+BUILD_VERSION)(?:[ \t]*=[ \t]*[^\r\n]*)?\r?$',
        { param($match) $match.Groups[1].Value + '=' + $FullVersion }
    )
}

foreach ($composeName in @('docker-compose.yml', 'docker-compose.cpu.yml', 'docker-compose.vaapi.yml')) {
    $composePath = Join-RepoPath @($composeName)
    Update-Text $composePath {
        param($text)
        [regex]::Replace(
            $text,
            '(?m)^(\s*BUILD_VERSION:\s*)[^\r\n]+',
            { param($match) $match.Groups[1].Value + '"${APP_VERSION:-' + $FullVersion + '}"' }
        )
    }
}

$workflowRoot = Join-RepoPath @('.github', 'workflows')
if (Test-Path -LiteralPath $workflowRoot) {
    foreach ($workflow in Get-ChildItem -LiteralPath $workflowRoot -Recurse -File -Include *.yml,*.yaml) {
        Update-Text $workflow.FullName {
            param($text)
            $text -replace '(?m)^(\s*)APP_VERSION\s*=\s*[0-9]+(?:\.[0-9]+){0,3}\s*$', '$1APP_VERSION=$(tr -d ''\r\n '' < VERSION)'
        }
    }
}

$packageFiles = @(
    (Join-RepoPath @('frontend', 'package.json')),
    (Join-RepoPath @('package.json'))
)
foreach ($packagePath in $packageFiles) {
    if (Test-Path -LiteralPath $packagePath) {
        $package = Get-Content -LiteralPath $packagePath -Raw | ConvertFrom-Json
        if ($null -ne $package.version) {
            Update-Text $packagePath {
                param($text)
                return [regex]::Replace(
                    $text,
                    '(?m)^(\s*"version"\s*:\s*")[^"]+(".*)$',
                    { param($match) $match.Groups[1].Value + $DisplayVersion + $match.Groups[2].Value }
                )
            }
        }
    }
}

# The current lockfile has no root package version. If a future lockfile adds
# one, package.json remains the authoritative npm metadata and the lockfile is
# checked by the version test rather than modified by a broad replacement.

$windowsRoot = Join-RepoPath @('windows')
if (Test-Path -LiteralPath $windowsRoot) {
    $desktopLauncher = Join-RepoPath @('windows', 'desktop_app.py')
    if (Test-Path -LiteralPath $desktopLauncher -PathType Leaf) {
        Update-Text $desktopLauncher {
            param($text)
            return [regex]::Replace(
                $text,
                '(?m)^(\s*DESKTOP_VERSION\s*=\s*["''])[^"'']*(["''])',
                { param($match) $match.Groups[1].Value + $FullVersion + $match.Groups[2].Value }
            )
        }
    }
    $installerFiles = @(
        (Join-RepoPath @('windows', 'installer.iss'))
    ) | Where-Object { Test-Path -LiteralPath $_ -PathType Leaf }
    foreach ($filePath in $installerFiles) {
        $file = Get-Item -LiteralPath $filePath
        Update-Text $file.FullName {
            param($text)
            $result = [regex]::Replace(
                $text,
                '(?im)^(\s*#define\s+\w*Version\s+")([^"]+)(")',
                { param($match) $match.Groups[1].Value + $FullVersion + $match.Groups[3].Value }
            )
            $result = [regex]::Replace(
                $result,
                '(?im)^(\s*AppVersion\s*=\s*)[^;\r\n]+',
                { param($match) $match.Groups[1].Value + '{#MyAppVersion}' }
            )
            return $result
        }
    }
    $manifestFiles = @(
        (Join-RepoPath @('windows', 'msix', 'AppxManifest.xml')),
        (Join-RepoPath @('windows', 'AppxManifest.xml'))
    ) | Where-Object { Test-Path -LiteralPath $_ -PathType Leaf }
    foreach ($filePath in $manifestFiles) {
        $file = Get-Item -LiteralPath $filePath
        Update-Text $file.FullName {
            param($text)
            return [regex]::Replace(
                $text,
                '(?i)(?<![A-Za-z])(Version\s*=\s*")[^"]+(")',
                { param($match) $match.Groups[1].Value + $FullVersion + $match.Groups[2].Value }
            )
        }
    }
    $resourceFiles = @(
        (Join-RepoPath @('windows', 'version_info.txt')),
        (Join-RepoPath @('windows', 'version-info.txt')),
        (Join-RepoPath @('windows', 'version.rc'))
    ) | Where-Object { Test-Path -LiteralPath $_ -PathType Leaf }
    $resourceFiles += @(Get-ChildItem -LiteralPath $windowsRoot -File -Filter '*.rc' -ErrorAction SilentlyContinue | ForEach-Object { $_.FullName })
    foreach ($filePath in $resourceFiles | Select-Object -Unique) {
        $file = Get-Item -LiteralPath $filePath
        Update-Text $file.FullName {
            param($text)
            $result = [regex]::Replace(
                $text,
                '(?im)^(\s*FILEVERSION\s+)[0-9,\s]+',
                { param($match) $match.Groups[1].Value + ($Parts -join ',') }
            )
            $result = [regex]::Replace(
                $result,
                '(?im)^(\s*PRODUCTVERSION\s+)[0-9,\s]+',
                { param($match) $match.Groups[1].Value + ($Parts -join ',') }
            )
            $result = [regex]::Replace(
                $result,
                '(?im)(VALUE\s+"FileVersion"\s*,\s*")[^"]+(")',
                { param($match) $match.Groups[1].Value + $FullVersion + $match.Groups[2].Value }
            )
            $result = [regex]::Replace(
                $result,
                '(?im)(VALUE\s+"ProductVersion"\s*,\s*")[^"]+(")',
                { param($match) $match.Groups[1].Value + $FullVersion + $match.Groups[2].Value }
            )
            if ($file.Name -match '^version_info\.txt$|^version-info\.txt$') {
                # PyInstaller version files use Python tuple/string syntax,
                # not the C resource syntax handled above.
                $result = [regex]::Replace(
                    $result,
                    '(?im)(^\s*filevers\s*=\s*\()[^\)]*(\))',
                    { param($match) $match.Groups[1].Value + ($Parts -join ', ') + $match.Groups[2].Value }
                )
                $result = [regex]::Replace(
                    $result,
                    '(?im)(^\s*prodvers\s*=\s*\()[^\)]*(\))',
                    { param($match) $match.Groups[1].Value + ($Parts -join ', ') + $match.Groups[2].Value }
                )
                $result = [regex]::Replace(
                    $result,
                    '(?im)(StringStruct\("FileVersion",\s*")[^"]+("\))',
                    { param($match) $match.Groups[1].Value + $FullVersion + $match.Groups[2].Value }
                )
                $result = [regex]::Replace(
                    $result,
                    '(?im)(StringStruct\("ProductVersion",\s*")[^"]+("\))',
                    { param($match) $match.Groups[1].Value + $DisplayVersion + $match.Groups[2].Value }
                )
            }
            return $result
        }
    }
}

Write-Output ("VERSION_SET=" + $FullVersion)
Write-Output ("VERSION_DISPLAY=" + $DisplayVersion)
if ($Changed.Count -eq 0) {
    Write-Output 'CHANGED_FILES=none'
} else {
    Write-Output 'CHANGED_FILES='
    foreach ($path in $Changed) {
        Write-Output ("CHANGED: " + $path)
    }
}
